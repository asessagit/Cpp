// 2. Operações de comparação em C++:
int number1;
int number2;

std::cout << "Enter first number: ";
std::cin >> number1;
std::cout << "Enter second number: ";
std::cin >> number2;// 

if (number1 == number2)
    cout << number1 << "==" << number2 << std::endl;
if (number1 != number2)
    cout << number1 << "!=" << number2 << std::endl;
if (number1 > number2)
    cout << number1 << ">" << number2 << std::endl;
if (number1 < number2)
    cout << number1 << "<" << number2 << std::endl;
if (number1 >= number2)
    cout << number1 << ">=" << number2 << std::endl;
if (number1 <= number2)
    cout << number1 << "<=" << number2 << std::endl;